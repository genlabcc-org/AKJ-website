create table if not exists public.blogs (
  id bigint generated by default as identity primary key,
  title text not null,
  category text,
  content text,
  thumb text,
  images text[],
  author text not null,
  avatar text,
  is_admin_icon boolean default false,
  read_time text,
  publish_date text not null,
  status text not null default 'Published',
  created_at timestamptz default now()
);

-- Ensure columns exist if public.blogs was created with an earlier schema
alter table public.blogs add column if not exists category text;
alter table public.blogs add column if not exists content text;
alter table public.blogs add column if not exists images text[];
notify pgrst, 'reload schema';

create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  title text not null,
  video_url text,
  thumb text,
  session_date text not null,
  status text not null default 'Published',
  created_at timestamptz default now()
);

-- Migrate legacy video columns into video_url and remove unwanted columns
alter table public.videos add column if not exists video_url text;
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'videos' and column_name = 'avatar'
  ) then
    execute 'update public.videos set video_url = avatar where video_url is null and avatar is not null and avatar like ''http%''';
  end if;
end $$;
alter table public.videos
  drop column if exists host,
  drop column if exists avatar,
  drop column if exists is_admin_icon,
  drop column if exists duration;
notify pgrst, 'reload schema';

-- Enable Row Level Security and allow public/anon read & write for Admin Panel
alter table public.blogs enable row level security;
alter table public.videos enable row level security;

drop policy if exists "Allow all operations on blogs" on public.blogs;
create policy "Allow all operations on blogs"
  on public.blogs for all
  using (true)
  with check (true);

drop policy if exists "Allow all operations on videos" on public.videos;
create policy "Allow all operations on videos"
  on public.videos for all
  using (true)
  with check (true);

-- Public storage bucket for blog cover/article images
insert into storage.buckets (id, name, public)
values ('blog-images', 'blog-images', true)
on conflict (id) do update set public = true;

drop policy if exists "Public read access on blog-images" on storage.objects;
create policy "Public read access on blog-images"
  on storage.objects for select
  using (bucket_id = 'blog-images');

drop policy if exists "Allow upload to blog-images" on storage.objects;
create policy "Allow upload to blog-images"
  on storage.objects for insert
  with check (bucket_id = 'blog-images');

drop policy if exists "Allow update on blog-images" on storage.objects;
create policy "Allow update on blog-images"
  on storage.objects for update
  using (bucket_id = 'blog-images');

drop policy if exists "Allow delete on blog-images" on storage.objects;
create policy "Allow delete on blog-images"
  on storage.objects for delete
  using (bucket_id = 'blog-images');

