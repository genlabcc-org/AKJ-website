create table if not exists public.blogs (
  id bigint generated by default as identity primary key,
  title text not null,
  category text default 'University Guide',
  content text default '',
  thumb text default '/images/blog-1.jpg',
  images text[] default array['/images/blog-1.jpg'],
  author text not null default 'Margaret',
  avatar text default '/images/testimonial-1.jpg',
  is_admin_icon boolean default false,
  read_time text default '5 min read',
  publish_date text not null,
  status text not null default 'Published',
  created_at timestamptz default now()
);

create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  title text not null,
  thumb text default '/images/blog-2.jpg',
  host text not null default 'Margaret',
  avatar text default '/images/testimonial-2.jpg',
  is_admin_icon boolean default false,
  duration text default '45 mins',
  session_date text not null,
  status text not null default 'Published',
  created_at timestamptz default now()
);

-- Enable Row Level Security and allow public/anon read & write for Admin Panel
alter table public.blogs enable row level security;
alter table public.videos enable row level security;

create policy "Allow all operations on blogs"
  on public.blogs for all
  using (true)
  with check (true);

create policy "Allow all operations on videos"
  on public.videos for all
  using (true)
  with check (true);
