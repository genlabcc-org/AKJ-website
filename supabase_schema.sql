-- Run this in your Supabase SQL Editor

create table if not exists public.blogs (
  id bigint generated by default as identity primary key,
  title text not null,
  category text,
  content text,
  thumb text,
  images text[],
  author text not null,
  avatar text,
  is_admin_icon boolean default false,
  read_time text,
  publish_date text not null,
  status text not null default 'Published',
  created_at timestamptz default now()
);

create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  title text not null,
  thumb text,
  host text not null,
  avatar text,
  is_admin_icon boolean default false,
  duration text,
  session_date text not null,
  status text not null default 'Published',
  created_at timestamptz default now()
);

-- Enable Row Level Security and allow public/anon read & write for Admin Panel
alter table public.blogs enable row level security;
alter table public.videos enable row level security;

create policy "Allow all operations on blogs"
  on public.blogs for all
  using (true)
  with check (true);

create policy "Allow all operations on videos"
  on public.videos for all
  using (true)
  with check (true);

-- Public storage bucket for blog cover/article images
insert into storage.buckets (id, name, public)
values ('blog-images', 'blog-images', true)
on conflict (id) do update set public = true;

create policy "Public read access on blog-images"
  on storage.objects for select
  using (bucket_id = 'blog-images');

create policy "Allow upload to blog-images"
  on storage.objects for insert
  with check (bucket_id = 'blog-images');

create policy "Allow update on blog-images"
  on storage.objects for update
  using (bucket_id = 'blog-images');

create policy "Allow delete on blog-images"
  on storage.objects for delete
  using (bucket_id = 'blog-images');
